/**
 * Round-6 judge ruling: whether a title like "Monday, 6h59m PM" was typed by
 * a human is UNDECIDABLE from the string — the shape heuristic got reversed
 * twice, so it was DELETED. What remains is provenance only: the one fact
 * creation code actually knows (who chose the name). Legacy rows (mark
 * undefined) fall back to GENERATED_TITLE_PATTERN in shouldReplaceVideoTitle
 * — the closed set of literal template strings this codebase itself
 * generates.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { titleOriginMetadata } from "@/lib/title-origin";
import { titleFromFileName } from "@/lib/video-title";

describe("titleOriginMetadata — provenance only, no string guessing", () => {
	it("ANY existing title is presumed human-chosen — including ones another tool auto-named", () => {
		expect(
			titleOriginMetadata(titleFromFileName("Q3 board meeting.mp4")),
		).toEqual({});
		expect(titleOriginMetadata("Sprint review 10:30")).toEqual({});
		expect(titleOriginMetadata("2026-08-10 team sync")).toEqual({});
		// The deleted heuristic used to mark this one — provenance cannot know
		// who named the file, so it is protected now (accepted consequence:
		// the AI will not rename it; the owner can).
		expect(
			titleOriginMetadata(titleFromFileName("Monday, 6h59m PM (1).mp4")),
		).toEqual({});
	});

	it("only the dated-template fallback (no title at all) is marked machine-derived", () => {
		expect(titleOriginMetadata(titleFromFileName(undefined))).toEqual({
			titleAutoGenerated: true,
		});
		expect(titleOriginMetadata(null)).toEqual({ titleAutoGenerated: true });
		expect(titleOriginMetadata("   ")).toEqual({ titleAutoGenerated: true });
	});

	it("the shape heuristic is DELETED, not merely unused", () => {
		const src = readFileSync(
			fileURLToPath(new URL("../../lib/title-origin.ts", import.meta.url)),
			"utf8",
		);
		expect(src).not.toContain("isMachineFormattedTitle");
	});
});

describe("creation sites route the mark through the helper (no raw literal)", () => {
	const CREATION_FILES = [
		"../../actions/video/create-for-processing.ts",
		"../../actions/video/upload.ts",
		"../../actions/loom.ts",
		"../../app/api/desktop/[...route]/video.ts",
	];

	for (const rel of CREATION_FILES) {
		it(`${rel} never writes titleAutoGenerated: true directly`, () => {
			const src = readFileSync(
				fileURLToPath(new URL(rel, import.meta.url)),
				"utf8",
			);
			expect(src).not.toMatch(/titleAutoGenerated:\s*true/);
			expect(src).toMatch(/titleOriginMetadata\(/);
		});
	}
});
