import type { VideoMetadata } from "@cap/database/types";

/**
 * Does this title look like something a MACHINE formatted, not a human typed?
 *
 * Needed because a "human-chosen" title is sometimes only human-SELECTED: the
 * file-import path receives the name of a file the user picked from disk, and
 * that file may have been auto-named by another recorder (the owner's real
 * case: `Monday, 6h59m PM (1)`). Treating the whole branch as human switched
 * AI auto-rename OFF for exactly the recordings that most need a real title;
 * treating it as machine would let the AI overwrite genuinely human names
 * like "Q3 board meeting". So: conservative shape check — only confident
 * machine patterns match, anything else is presumed human and protected.
 *
 * Patterns (checked after stripping a trailing " (n)" duplicate counter):
 *  - a time-of-day token: "6h59m PM", "14:32:05", "2.45 PM"
 *  - an ISO-ish date: "2026-08-10", "2026_08_10"
 *  - camera/recorder defaults: "IMG_1234", "VID-20260810", "REC 003",
 *    "Screen Recording", "Screenrecorder-...", "Untitled"
 *  - a weekday followed by a comma ("Monday, ...") — locale date formatting,
 *    not a way humans start titles.
 */
const MACHINE_TITLE_PATTERNS: RegExp[] = [
	// Time-of-day token: "6h59m PM", "2.45 PM", "14:32", "14:32:05"
	/\b\d{1,2}[:h.]\d{2}(?:m|:\d{2})?\s*(?:AM|PM)\b/i,
	/\b\d{1,2}:\d{2}(?::\d{2})?\b/,
	// ISO-ish date: "2026-08-10", "2026_08_10", "2026.08.10"
	/\b\d{4}[-_.]\d{2}[-_.]\d{2}\b/,
	// Camera / phone recorder defaults: "IMG_1234", "VID-20260810", "REC 003"
	/^(?:IMG|VID|MOV|REC|DSC)[-_ ]?\d+/i,
	// Screen recorder defaults
	/^screen[-_ ]?record/i,
	/^screenrecorder\b/i,
	/^untitled\b/i,
	// Locale date formatting starts with a weekday + comma ("Monday, ...") —
	// not a way humans start titles.
	/^(?:Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday),/i,
];

export function isMachineFormattedTitle(title: string): boolean {
	const t = title
		.trim()
		// " (1)", " (12)" duplicate-file counters don't change the verdict.
		.replace(/\s*\(\d+\)\s*$/, "");
	if (!t) return true;
	return MACHINE_TITLE_PATTERNS.some((pattern) => pattern.test(t));
}

/**
 * Title-origin metadata for a NEWLY CREATED video.
 *
 * Pass the candidate HUMAN title if one exists — the file name the user
 * picked for an upload, Loom's own video title, a name typed in the recorder
 * — or null/undefined when the system fell back to a dated template
 * ("data365 Recording - <date>", "Loom Import - <date>", ...).
 *
 * `titleAutoGenerated` is written when the template named the video OR when
 * the candidate title is itself machine-formatted (see
 * isMachineFormattedTitle) — both cases are names no human composed, so the
 * AI auto-title may replace them. A genuinely human name gets no mark and is
 * never renamed. Creation sites must build the flag through this helper (a
 * test enforces that no creation site writes the raw literal), so the
 * human/machine decision lives in exactly one place.
 */
export function titleOriginMetadata(
	humanChosenTitle: string | null | undefined,
): Pick<VideoMetadata, "titleAutoGenerated"> {
	const title = humanChosenTitle?.trim();
	if (!title) return { titleAutoGenerated: true };
	return isMachineFormattedTitle(title) ? { titleAutoGenerated: true } : {};
}
